import { compile } from "json-schema-to-typescript";
import type { EntityDefinition } from "./schema.js";

const HEADER = `// Auto-generated by Base44 CLI - DO NOT EDIT
// Regenerate with: base44 types
`;

/** Options for json-schema-to-typescript */
const COMPILE_OPTIONS = {
  bannerComment: "",
  additionalProperties: false,
  strictIndexSignatures: true,
  enableConstEnums: true,
  declareExternallyReferenced: false,
};

/**
 * Generate TypeScript interface from JSON Schema using json-schema-to-typescript
 */
async function generateEntityInterface(entity: EntityDefinition): Promise<string> {
  // Add title for the interface name
  const schema = {
    ...entity,
    title: entity.name,
    $schema: "http://json-schema.org/draft-07/schema#",
  };

  const result = await compile(schema, entity.name, COMPILE_OPTIONS);

  // Modify to extend BaseEntity
  return result.replace(
    `export interface ${entity.name} {`,
    `export interface ${entity.name} extends BaseEntity {`
  );
}

/**
 * Generate CreateInput type (same as entity but without system fields)
 */
async function generateCreateInput(entity: EntityDefinition): Promise<string> {
  const schema = {
    ...entity,
    title: `${entity.name}CreateInput`,
    $schema: "http://json-schema.org/draft-07/schema#",
  };

  return await compile(schema, `${entity.name}CreateInput`, COMPILE_OPTIONS);
}

/**
 * Generate UpdateInput type (all fields optional)
 */
async function generateUpdateInput(entity: EntityDefinition): Promise<string> {
  const schema = {
    ...entity,
    title: `${entity.name}UpdateInput`,
    required: [], // All fields optional for updates
    $schema: "http://json-schema.org/draft-07/schema#",
  };

  return await compile(schema, `${entity.name}UpdateInput`, COMPILE_OPTIONS);
}

/**
 * Generate Filter type (all fields optional for querying)
 */
async function generateFilterType(entity: EntityDefinition): Promise<string> {
  const schema = {
    ...entity,
    title: `${entity.name}Filter`,
    required: [], // All fields optional for filters
    $schema: "http://json-schema.org/draft-07/schema#",
  };

  return await compile(schema, `${entity.name}Filter`, COMPILE_OPTIONS);
}

/**
 * Generate all types for a single entity
 */
async function generateEntityTypes(entity: EntityDefinition): Promise<string> {
  const [mainInterface, createInput, updateInput, filterType] = await Promise.all([
    generateEntityInterface(entity),
    generateCreateInput(entity),
    generateUpdateInput(entity),
    generateFilterType(entity),
  ]);

  return `${mainInterface}\n${createInput}\n${updateInput}\n${filterType}`;
}

/**
 * Generate the entities.ts file content
 */
export async function generateEntitiesFile(entities: EntityDefinition[]): Promise<string> {
  const baseEntity = `
/** System fields present on all entities */
export interface BaseEntity {
  id: string;
  created_date: string;
  updated_date: string;
}
`;

  const entityTypes = await Promise.all(entities.map(generateEntityTypes));

  // Generate union type of all entity names
  const entityNames = entities.map((e) => `'${e.name}'`).join(" | ");
  const entityNamesType = entities.length > 0
    ? `\n/** All entity names in this project */\nexport type EntityName = ${entityNames};\n`
    : "";

  return HEADER + baseEntity + entityTypes.join("\n") + entityNamesType;
}

/**
 * Generate the client.ts file content with typed SDK wrapper
 */
export function generateClientFile(entities: EntityDefinition[]): string {
  if (entities.length === 0) {
    return HEADER + "\n// No entities found\nexport {};\n";
  }

  // Generate imports
  const imports = entities
    .map((e) => `${e.name}, ${e.name}CreateInput, ${e.name}UpdateInput, ${e.name}Filter`)
    .join(",\n  ");

  // Generate entity handlers
  const handlers = entities
    .map(
      (e) =>
        `  ${e.name}: EntityHandler<${e.name}, ${e.name}CreateInput, ${e.name}UpdateInput, ${e.name}Filter>;`
    )
    .join("\n");

  return `${HEADER}
import type {
  ${imports}
} from './entities.js';

/** Response for list/filter operations */
export interface ListResponse<T> {
  items: T[];
  total: number;
}

/** Real-time subscription event */
export interface RealtimeEvent<T> {
  type: 'create' | 'update' | 'delete';
  data: T;
  id: string;
  timestamp: string;
}

/** Entity handler with CRUD operations */
export interface EntityHandler<T, TCreate, TUpdate, TFilter> {
  /** Get all records with optional pagination */
  list(sort?: string, limit?: number, skip?: number, fields?: (keyof T)[]): Promise<ListResponse<T>>;
  /** Get records matching filter criteria */
  filter(query: TFilter, sort?: string, limit?: number, skip?: number, fields?: (keyof T)[]): Promise<ListResponse<T>>;
  /** Get a single record by ID */
  get(id: string): Promise<T>;
  /** Create a new record */
  create(data: TCreate): Promise<T>;
  /** Update an existing record */
  update(id: string, data: TUpdate): Promise<T>;
  /** Delete a record */
  delete(id: string): Promise<void>;
  /** Delete multiple records matching filter */
  deleteMany(query: TFilter): Promise<void>;
  /** Create multiple records at once */
  bulkCreate(data: TCreate[]): Promise<T[]>;
  /** Subscribe to real-time updates */
  subscribe(callback: (event: RealtimeEvent<T>) => void): () => void;
}

/** Typed entities interface for Base44 SDK */
export interface TypedEntities {
${handlers}
}

/**
 * Typed Base44 client interface.
 * Use with the Base44 SDK for type-safe entity access.
 *
 * @example
 * import { createClient } from '@base44/sdk';
 * import type { TypedBase44Client } from './base44/client';
 *
 * const base44 = createClient({ appId: 'your-app-id' }) as TypedBase44Client;
 * const tasks = await base44.entities.Task.list();
 */
export interface TypedBase44Client {
  entities: TypedEntities;
}
`;
}

/**
 * Generate the index.ts barrel file
 */
export function generateIndexFile(): string {
  return `${HEADER}
export * from './entities.js';
export * from './client.js';
`;
}
